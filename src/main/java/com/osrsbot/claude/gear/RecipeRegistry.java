package com.osrsbot.claude.gear;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.runelite.api.Client;
import net.runelite.api.Quest;
import net.runelite.api.QuestState;
import net.runelite.api.Skill;
import net.runelite.api.WorldType;

import javax.inject.Singleton;
import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * All OSRS production recipes, keyed by ingredient name (lowercased).
 * Backed by {@code recipes.json}, generated by {@code tools/generate_recipes.py}
 * scraping the OSRS Wiki's {{Recipe|...}} templates from every item page.
 *
 * <p>Used to inject a [NEW_INGREDIENT_RECIPES] block into the prompt when an
 * item first appears in the player's inventory — telling the model what they
 * could make with it, where, and whether they meet the requirements.
 */
@Singleton
public class RecipeRegistry
{
    private static final String RESOURCE = "/recipes.json";

    /** Ingredient name (lowercased) → list of recipes that use it. */
    private final Map<String, List<Recipe>> byIngredient = new HashMap<>();
    /** Resolved Quest enum lookup by display name. */
    private final Map<String, Quest> questByName = new HashMap<>();

    public RecipeRegistry()
    {
        for (Quest q : Quest.values())
        {
            try
            {
                String n = q.getName();
                if (n != null) questByName.put(n.toLowerCase(Locale.ROOT), q);
            }
            catch (Throwable ignored) {}
        }
        load();
    }

    private void load()
    {
        try (InputStream in = RecipeRegistry.class.getResourceAsStream(RESOURCE))
        {
            if (in == null)
            {
                System.err.println("[ClaudeBot] recipes.json missing from resources — recipe annotations disabled");
                return;
            }
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
            int count = 0;
            for (Map.Entry<String, JsonElement> e : root.entrySet())
            {
                JsonArray arr = e.getValue().getAsJsonArray();
                List<Recipe> recipes = new ArrayList<>(arr.size());
                for (JsonElement el : arr)
                {
                    Recipe r = parseRecipe(el.getAsJsonObject());
                    if (r != null) recipes.add(r);
                }
                byIngredient.put(e.getKey().toLowerCase(Locale.ROOT), recipes);
                count += recipes.size();
            }
            System.out.println("[ClaudeBot] recipes loaded: "
                + byIngredient.size() + " ingredients, " + count + " recipe entries");
        }
        catch (Throwable t)
        {
            System.err.println("[ClaudeBot] failed to load recipes.json: " + t.getMessage());
            t.printStackTrace(System.err);
        }
    }

    private Recipe parseRecipe(JsonObject o)
    {
        Recipe r = new Recipe();
        r.page = optString(o, "page");
        r.outputs = stringArray(o, "outputs");
        r.facilities = optString(o, "facilities");
        r.members = o.has("members") && !o.get("members").isJsonNull() && o.get("members").getAsBoolean();
        r.questName = optString(o, "quest");
        if (r.questName != null && !r.questName.isEmpty())
        {
            r.quest = questByName.get(r.questName.toLowerCase(Locale.ROOT));
        }
        if (o.has("skills") && o.get("skills").isJsonArray())
        {
            for (JsonElement el : o.getAsJsonArray("skills"))
            {
                JsonObject sk = el.getAsJsonObject();
                String name = optString(sk, "skill");
                int level = sk.has("level") && !sk.get("level").isJsonNull() ? sk.get("level").getAsInt() : 1;
                if (name != null && !name.isEmpty())
                {
                    r.skills.add(new RecipeSkill(name, level));
                }
            }
        }
        if (o.has("ingredients") && o.get("ingredients").isJsonArray())
        {
            for (JsonElement el : o.getAsJsonArray("ingredients"))
            {
                JsonObject ing = el.getAsJsonObject();
                String name = optString(ing, "name");
                String qty = optString(ing, "qty");
                if (name != null && !name.isEmpty())
                {
                    r.ingredients.add(new Ingredient(name, qty != null ? qty : "1"));
                }
            }
        }
        return r;
    }

    private static String optString(JsonObject o, String key)
    {
        if (!o.has(key) || o.get(key).isJsonNull()) return null;
        return o.get(key).getAsString();
    }

    private static List<String> stringArray(JsonObject o, String key)
    {
        if (!o.has(key) || !o.get(key).isJsonArray()) return Collections.emptyList();
        List<String> out = new ArrayList<>();
        for (JsonElement el : o.getAsJsonArray(key))
        {
            if (!el.isJsonNull()) out.add(el.getAsString());
        }
        return out;
    }

    /** All recipes that use {@code ingredientName} as an input. Empty list
     *  if none known. Caller can filter by satisfaction status. */
    public List<Recipe> recipesUsing(String ingredientName)
    {
        if (ingredientName == null) return Collections.emptyList();
        List<Recipe> r = byIngredient.get(ingredientName.toLowerCase(Locale.ROOT).trim());
        return r != null ? r : Collections.<Recipe>emptyList();
    }

    /** Whether the given player meets all gates of a recipe (skills,
     *  membership, quest). */
    public static boolean isSatisfied(Client client, Recipe r)
    {
        if (r == null) return true;
        for (RecipeSkill s : r.skills)
        {
            Skill skill = skillForName(s.skill);
            if (skill == null) continue;
            int level;
            try { level = client.getRealSkillLevel(skill); }
            catch (Throwable t) { return false; }
            if (level < s.level) return false;
        }
        if (r.members)
        {
            try
            {
                Set<WorldType> wt = client.getWorldType();
                if (wt == null || !wt.contains(WorldType.MEMBERS)) return false;
            }
            catch (Throwable t) { return false; }
        }
        if (r.quest != null)
        {
            try
            {
                if (r.quest.getState(client) != QuestState.FINISHED) return false;
            }
            catch (Throwable t) { return false; }
        }
        // questName present but quest unresolved -> we don't know, treat as
        // unsatisfied so the LLM gets a hint to investigate.
        if (r.quest == null && r.questName != null && !r.questName.isEmpty()) return false;
        return true;
    }

    /** Resolve a wiki skill display name (e.g. "Smithing", "Ranged",
     *  "Magic", "Runecraft") to RuneLite's Skill enum. */
    private static Skill skillForName(String name)
    {
        if (name == null) return null;
        switch (name.toLowerCase(Locale.ROOT).trim())
        {
            case "attack":      return Skill.ATTACK;
            case "strength":    return Skill.STRENGTH;
            case "defence":
            case "defense":     return Skill.DEFENCE;
            case "ranged":      return Skill.RANGED;
            case "magic":       return Skill.MAGIC;
            case "hitpoints":
            case "hp":          return Skill.HITPOINTS;
            case "prayer":      return Skill.PRAYER;
            case "woodcutting": return Skill.WOODCUTTING;
            case "mining":      return Skill.MINING;
            case "fishing":     return Skill.FISHING;
            case "cooking":     return Skill.COOKING;
            case "firemaking":  return Skill.FIREMAKING;
            case "crafting":    return Skill.CRAFTING;
            case "smithing":    return Skill.SMITHING;
            case "fletching":   return Skill.FLETCHING;
            case "slayer":      return Skill.SLAYER;
            case "farming":     return Skill.FARMING;
            case "construction":return Skill.CONSTRUCTION;
            case "hunter":      return Skill.HUNTER;
            case "agility":     return Skill.AGILITY;
            case "thieving":    return Skill.THIEVING;
            case "herblore":    return Skill.HERBLORE;
            case "runecraft":
            case "runecrafting":return Skill.RUNECRAFT;
            default:            return null;
        }
    }

    public static final class Recipe
    {
        public String page;
        public List<String> outputs = new ArrayList<>();
        public final List<RecipeSkill> skills = new ArrayList<>();
        public boolean members;
        public Quest quest;        // resolved RuneLite enum, or null
        public String questName;   // raw display name from JSON
        public String facilities;  // anvil / range / spinning wheel / etc.
        public final List<Ingredient> ingredients = new ArrayList<>();
    }

    public static final class RecipeSkill
    {
        public final String skill;
        public final int level;
        public RecipeSkill(String skill, int level) { this.skill = skill; this.level = level; }
    }

    public static final class Ingredient
    {
        public final String name;
        public final String qty;
        public Ingredient(String name, String qty) { this.name = name; this.qty = qty; }
    }
}
